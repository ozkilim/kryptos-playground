"""Idea 113: Quagmire IV with BOTH alphabets hidden and a key of 8 numbers, searched through the plain alphabet.

Why: ABSCISSA has 8 letters and the K3 grid is 8 wide. Idea 99 showed that with any fixed alphabet on one side,
a repeating key of 1-7 or 9-12 cannot fit K4's clue letters; length 8 is the one short repeating key left when
both alphabets are free, and the community annealers (Quagmire I/II/IV at L=8 by English score) had no power
there. At length 8 the 14 clue cipher letters and the 8 key slots fall into two pieces (11 letters + slots
0-5,7, and G L Z + slot 6), and there are 4 closed loops. With both alphabets hidden every loop is a check on
the places of the 13 clue plain letters (A B C E H I K L N O R S T) only:

    2T + O = N + L + S,   K + S + N = A + T + I,   B + E = H + O,   C + T = R + S      (mod 26, repeating key)

What is searched (kryptos/idea113_both.py):
* every placing of the 13 clue plain letters on distinct places that closes all 4 loops AND puts the 14 clue
  cipher letters on distinct places within each piece, up to the two symmetries that change nothing (shift
  everything; multiply everything by a unit mod 26, which also turns Vigenere into Beaufort form). This is
  exhaustive, not sampled: every survivor is generated by nested loops with the 4 loops solved for 4 letters.
* for each survivor the 45 positions of K4 whose cipher letter is a clue cipher letter with its key slot in the
  same piece are forced to a place of the plain alphabet; the place holds a clue plain letter or one of the
  other 13 letters ('?'). Each survivor is scored by an order-3 Markov chain over these classes, taken from
  the big quadgram model (a proper likelihood of the forced pattern under English). The best 500 are kept.
* the best 500 are completed by simulated annealing (the 13 other plain letters, the 12 other cipher letters,
  the offset between the two pieces) on the big model, plus word coverage.
* sliding form (key = running sum of a word of 8, the strip moves by the word sum W each 8 letters): W = 13 is
  run in full (the multiplier symmetry still holds there). The other 24 sums fall into two classes (odd: W=1,
  even: W=2) but each costs 12 times the repeating search, so they are run on K4 only if IDEA113_SLIDE_ALL is set.
Controls: 3 shuffled K4s with the same piece structure (redrawn until they have 4 loops and pieces of 11 and 3).
Planted: 3 English messages with the real clue words, random alphabets on both sides and a random key of 8,
redrawn until their clue letters have the same structure as K4's; the rank of the true setting is reported.

  python attacks/113_both_hidden_length8.py
"""
import json
import os
import random
import sys
import time
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from kryptos import K4, CRIBS  # noqa: E402
from kryptos import idea113_both as B  # noqa: E402
from kryptos.ciphers import AZ  # noqa: E402
from kryptos.data import DATA_DIR  # noqa: E402
from kryptos.harness import Experiment  # noqa: E402
from kryptos.round9 import shuffled_control  # noqa: E402
from kryptos.round11 import english97, pmap  # noqa: E402
from kryptos.score import Quadgrams, word_coverage  # noqa: E402

SMOKE = os.environ.get("KRYPTOS_SMOKE")
PROCS = int(os.environ.get("IDEA113_PROCS", "4" if SMOKE else "12"))
NCTRL = int(os.environ.get("IDEA113_CONTROLS", "1" if SMOKE else "3"))
NPLANT = int(os.environ.get("IDEA113_PLANTS", "1" if SMOKE else "3"))
KEEP = 60 if SMOKE else 500
COMPLETE = int(os.environ.get("IDEA113_COMPLETE", "20" if SMOKE else "300"))
SLIDE_ALL = bool(os.environ.get("IDEA113_SLIDE_ALL"))
BIG = DATA_DIR / "english" / "quadgrams_big.txt"
ENGLISH = -5.1
G = {}


def init(ct, cribs, W, scale, T0, T, C):
    G["sys"], G["en"], G["order"], G["search"], _ = B.build(ct, cribs, W, scale)
    G["T"], G["T0"], G["C"] = T, T0, C


def work(chunk):
    out = []
    for doms, thr in chunk:
        out.append(G["search"](doms, G["T"], G["T0"], G["C"], KEEP, thr))
    return out


def search(ct, cribs, W, tables, true_score=1e300, must=None):
    scale = W in (0, 13)
    nfree = len(B.Enumerator(B.System(ct, cribs, W), scale).free)
    tasks = B.domains(nfree, scale)
    if SMOKE:
        keep = tasks[::9]
        if must is not None:
            keep += [t for t in tasks if t[0] == [must[0]] and t[1] == [must[1]] and t not in keep]
        tasks = keep
    tasks = [(d, true_score) for d in tasks]
    count = above = 0
    s1 = s2 = 0.0
    top = []
    for part in pmap(work, tasks, init, (ct, cribs, W, scale) + tables, chunk=1, procs=PROCS):
        for c, a, t, x1, x2 in part:
            count += c
            above += a
            top.extend(t)
            s1 += x1
            s2 += x2
    top.sort(key=lambda x: -x[0])
    mean = s1 / max(1, count)
    sd = max(1e-9, (s2 / max(1, count) - mean * mean)) ** 0.5
    return count, above, top[:KEEP], (mean, sd)


def comp_init(ct, cribs, W):
    G["sys"], G["en"], G["order"], _, _ = B.build(ct, cribs, W, W in (0, 13))
    G["big"] = Quadgrams(BIG)


def comp_work(chunk):
    out = []
    for n, sc, vals in chunk:
        X = B.leaf_to_X(G["en"], G["order"], vals)
        c = B.Completer(G["sys"], X, G["big"])
        full, pt = c.anneal(random.Random(113000 + n), 1500 if SMOKE else 5000, 2)
        if pt is None:
            continue
        out.append((n, sc, full, pt, B.forced_reading(G["sys"], X)))
    return out


def complete(ct, cribs, W, top):
    jobs = [(n, sc, vals) for n, (sc, vals) in enumerate(top[:COMPLETE])]
    rows = []
    for part in pmap(comp_work, jobs, comp_init, (ct, cribs, W), chunk=10, procs=PROCS):
        rows.extend(part)
    rows.sort(key=lambda r: -r[2])
    return rows


def run_text(label, ct, cribs, W, tables, verbose=True):
    t0 = time.time()
    count, _, top, (mean, sd) = search(ct, cribs, W, tables)
    rows = complete(ct, cribs, W, top)
    stage1 = [s for s, _ in top]
    full = [r[2] for r in rows]
    s = {"survivors": count, "best_forced": round(stage1[0], 3) if stage1 else None,
         "forced_mean": round(mean, 3), "forced_sd": round(sd, 3),
         "best_forced_z": round((stage1[0] - mean) / sd, 2) if stage1 else None,
         "top20_forced_z": round((sum(stage1[:20]) / max(1, len(stage1[:20])) - mean) / sd, 2) if stage1 else None,
         "top20_forced_mean": round(sum(stage1[:20]) / max(1, len(stage1[:20])), 3),
         "best_completed": round(full[0], 3) if full else None,
         "top20_completed_mean": round(sum(full[:20]) / max(1, len(full[:20])), 3),
         "best_cover": round(word_coverage(rows[0][3]), 2) if rows else None,
         "english": sum(1 for f in full if f > ENGLISH), "minutes": round((time.time() - t0) / 60, 1)}
    print("%s W=%d: %s" % (label, W, json.dumps(s)))
    for r in rows[:5 if verbose else 2]:
        print("   forced %.2f  completed %.3f  cover %.2f\n        %s\n        %s"
              % (r[1], r[2], word_coverage(r[3]), r[4], r[3]))
    sys.stdout.flush()
    return s, rows


# ---------------------------------------------------------------- controls and planted

def same_shape_control(seed0, W, want):
    s = seed0
    while True:
        ct = shuffled_control(s)
        sy = B.System(ct, CRIBS, W)
        if sy.shape() == want and sy.open_checks() and B.Enumerator(sy, W in (0, 13)).regular():
            return ct, s
        s += 1


def plant(rng, W, want):
    """English message with the clue words in place, random alphabets on both sides and a random key of 8 numbers
    (sliding with word sum W if W), redrawn until the clue letters have K4's structure."""
    pt = list(english97(rng))
    for i, ch in CRIBS.items():
        pt[i] = ch
    pt = "".join(pt)
    tries = 0
    while True:
        tries += 1
        pa, ca = "".join(rng.sample(AZ, 26)), "".join(rng.sample(AZ, 26))
        nums = [rng.randrange(26) for _ in range(B.L)]
        if W:
            nums[-1] = (W - sum(nums[:-1])) % 26
        beau = rng.random() < 0.5
        ct = B.quagmire4(pt, pa, ca, B.key_stream(nums, bool(W)), beau)
        sy = B.System(ct, CRIBS, W)
        if sy.shape() == want and sy.open_checks() and B.Enumerator(sy, W in (0, 13)).regular():
            return ct, pt, pa, beau, tries


def planted_case(rng, W, want, tables, big):
    ct, pt, pa, beau, tries = plant(rng, W, want)
    sysm = B.System(ct, CRIBS, W)
    en = B.Enumerator(sysm, W in (0, 13))
    order = en.plan_order()
    # Beaufort form = Vigenere with the plain alphabet back to front
    X = [((-1 if beau else 1) * pa.index(c)) % 26 for c in sysm.letters]
    vals, u = B.true_vals(en, order, X)
    Xc = B.leaf_to_X(en, order, vals)
    assert sysm.evaluate(Xc) is not None, "true setting fails the checks"
    fn = B.build(ct, CRIBS, W, W in (0, 13))[3]
    cnt, _, top, _, _ = fn(B.single(vals), tables[1], tables[0], tables[2], 1, 1e300)
    assert cnt == 1, "true setting not generated"
    true_sc = top[0][0]
    count, above, best, (mean, sd) = search(ct, CRIBS, W, tables, true_sc, must=vals)
    rank = above + 1
    rows = complete(ct, CRIBS, W, best)
    got = max([sum(a == b for a, b in zip(r[3], pt)) for r in rows], default=0)
    mine = [v for _, v in best if tuple(v) == tuple(vals)]
    print("planted W=%d %s (%d redraws): %d survivors, true setting forced score %.2f ranked %d (best %.2f); "
          "best completed reading %.3f with %d/97 letters right; true setting in the completed list: %s"
          % (W, "Beaufort" if beau else "Vigenere", tries, count, true_sc, rank, best[0][0] if best else 0,
             rows[0][2] if rows else 0, got, bool(mine)))
    if rows:
        print("        %s\n        %s" % (rows[0][3], pt))
    sys.stdout.flush()
    return {"W": W, "rank": rank, "survivors": count, "true_forced": round(true_sc, 3),
            "true_forced_z": round((true_sc - mean) / sd, 2), "best_forced_z": round((best[0][0] - mean) / sd, 2),
            "best_forced": round(best[0][0], 3) if best else None, "letters_read": got,
            "best_completed": round(rows[0][2], 3) if rows else None, "in_top": bool(mine),
            "read_back": bool(rows) and sum(a == b for a, b in zip(rows[0][3], pt)) >= 75}


if __name__ == "__main__":
    t0 = time.time()
    print("building class tables from the big model ...")
    k4sys = B.System(K4, CRIBS, 0)
    want = k4sys.shape()
    tables = B.class_tables(BIG, k4sys.letters)
    big = Quadgrams(BIG)
    print("K4 structure at key length 8: %d loops, pieces %s, %d clue plain letters, %d forced positions"
          % (want[0], want[1], want[2], len(k4sys.forced)))
    Ws = [0, 13] + ([1, 2] if SLIDE_ALL else [])
    with Experiment("Quagmire IV both alphabets hidden, key length 8 (repeating and sliding W=13)",
                    puzzle="k4", cribs_forced=True,
                    notes="exhaustive placings of the 13 clue plain letters closing the 4 loops at L=8 "
                          "(up to shift and unit multiple), forced-letter Markov score, top %d completed" % COMPLETE) as ex:
        out = {"k4": {}, "controls": {}, "planted": []}
        for W in Ws:
            wantW = B.System(K4, CRIBS, W).shape()
            k4s, rows = run_text("K4", K4, CRIBS, W, tables)
            out["k4"][W] = k4s
            ex.count(k4s["survivors"])
            for r in rows[:20]:
                ex.add(r[3], english_big=r[2], W=W, forced=r[1])
            ctrls = []
            seed = 11300 - 1
            for c in range(NCTRL):
                ct, seed = same_shape_control(seed + 1, W, wantW)     # distinct shuffles, same structure
                cs, _ = run_text("shuffled K4 #%d (seed %d)" % (c + 1, seed), ct, CRIBS, W, tables, verbose=False)
                ctrls.append(cs)
            out["controls"][W] = ctrls
            print("   (%.1f min)" % ((time.time() - t0) / 60))
        rng = random.Random(113)
        for k in range(NPLANT):
            out["planted"].append(planted_case(rng, 0, want, tables, big))
            print("   (%.1f min)" % ((time.time() - t0) / 60))
        if not SMOKE:
            out["planted"].append(planted_case(rng, 13, B.System(K4, CRIBS, 13).shape(), tables, big))
        first = sum(1 for p in out["planted"] if p["rank"] == 1)
        out["planted_rank1"] = "%d/%d" % (first, len(out["planted"]))
        sig = []
        for W in Ws:
            k = out["k4"][W]
            cb = [c["best_completed"] for c in out["controls"][W] if c["best_completed"] is not None] or [-99]
            cf = [c["best_forced_z"] for c in out["controls"][W] if c["best_forced_z"] is not None] or [-1e9]
            sig.append(k["best_completed"] > max(cb) + 0.1 and k["best_forced_z"] > max(cf) and k["english"] > 0)
        out["minutes"] = round((time.time() - t0) / 60, 1)
        print("RESULT " + json.dumps(out))
        verdict = ("K4 beats every control at some W - inspect by eye" if any(sig) else
                   "no signal: K4 does not beat the shuffled controls (planted ranked first %s)" % out["planted_rank1"])
        print("VERDICT:", verdict)
        ex.notes += "; " + verdict
