"""Idea 18: rank cipher FAMILIES by how often they produce K4's statistical
fingerprint (flat IoC, Stehle's lag-4 run, mod-7 doublets, Bean's width-21
repeats and "close" letters). No key search: this decides where the next big
searches should go.

Self-calibration: fake K4s made by known families are ranked the same way;
the median rank of the true family says how much to trust the ranking.
Writes campaign/FINGERPRINTS.md.
"""
import statistics
import sys
import time
from multiprocessing import Pool, cpu_count
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import random  # noqa: E402
from kryptos.campaign import CAMPAIGN, SMOKE, report  # noqa: E402
from kryptos import fingerprint as FP  # noqa: E402

M = 300 if SMOKE else 4000
CALIBRATE = ["columnar then periodic key", "ciphertext autokey", "periodic Vigenere 4-14, KRYPTOS (K1/K2 style)",
             "running key (English text), A-Z", "double columnar + periodic key", "random letters (one-time pad)"]
_T = {}


def _init():
    _T["text"] = FP.english_windows()
    _T["fams"] = FP.families(_T["text"])


def _sim(args):
    name, n, seed = args
    return FP.simulate(name, _T["fams"][name], _T["text"], n, seed)


if __name__ == "__main__":
    t0 = time.time()
    names = list(FP.families("X" * 200).keys())
    with Pool(cpu_count(), initializer=_init) as pool:
        table = dict(pool.map(_sim, [(n, M, 1000 + k) for k, n in enumerate(names)]))
    ranking = FP.rank(table, FP.K4_STATS)

    # self-calibration: hold out fresh fakes from known families
    text = FP.english_windows()
    fams = FP.families(text)
    rng = random.Random(4242)
    calib = {}
    for fam in CALIBRATE:
        ranks = []
        for _ in range(10 if SMOKE else 40):
            fake = fams[fam](FP.k4_like_plaintext(text, rng), rng)
            r = FP.rank(table, FP.stats(fake))
            ranks.append([x[1] for x in r].index(fam) + 1)
        calib[fam] = statistics.median(ranks)

    k4 = FP.K4_STATS
    lines = ["# Which cipher families make K4-like ciphertexts?", "",
             f"Generated by `attacks/18_fingerprint_ranking.py`. {M:,} simulated 97-letter English messages per family "
             "(EASTNORTHEAST / BERLINCLOCK in K4's positions), random keys.", "",
             f"K4's fingerprint: IoC {k4['ioc']:.4f}, Stehle run {k4['stehle']}, doublet clustering {k4['doublets']:.2f}, "
             f"repeated (c[i], c[i+w]) pairs {k4['vpairs']}, clue letters within 3 places {k4['close']}/24.", "",
             "Each cell is the fraction of that family's ciphertexts at least as odd as K4 on that statistic "
             "(IoC: within +-0.004). **Score** = sum of log10 of the five; higher = more K4-like. "
             "**Joint** = fraction matching K4 on all five at once.", "",
             "| Rank | Family | Score | IoC | Stehle | Doublets | Vpairs | Close | Joint |",
             "|---|---|---|---|---|---|---|---|---|"]
    for k, (score, fam, tp) in enumerate(ranking, 1):
        lines.append(f"| {k} | {fam} | {score:.2f} | " + " | ".join(f"{tp[s]:.3f}" for s in FP.STATS) +
                     f" | {tp['joint']:.4f} |")
    lines += ["", "## How much to trust this ranking", "",
              "Fake K4s were made by each family below and ranked against the same table. A median rank near 1 "
              f"means the ranking can recognise that family from its fingerprint (out of {len(ranking)}).", "",
              "| True family of the fake | Median rank |", "|---|---|"]
    lines += [f"| {f} | {r:g} |" for f, r in calib.items()]
    lines += ["", "Caveat: K4's oddities were noticed post hoc, so treat this as a soft prior on where to search, "
              "not as evidence for any one family."]
    out = CAMPAIGN / ("FINGERPRINTS.md" if not SMOKE else "FINGERPRINTS.smoke.md")
    out.write_text("\n".join(lines) + "\n")
    top = [f"{fam} ({score:.2f})" for score, fam, _ in ranking[:3]]
    bottom = [f"{fam} ({score:.2f})" for score, fam, _ in ranking[-3:]]
    verdict = f"most K4-like: {'; '.join(top)}. Least: {'; '.join(bottom)}. See campaign/FINGERPRINTS.md"
    report("18", name="fingerprint ranking of cipher families", k4_stats=k4, sims_per_family=M,
           ranking=[{"family": f, "score": round(s, 3), **{k: round(v, 4) for k, v in tp.items()}}
                    for s, f, tp in ranking], calibration=calib, verdict=verdict,
           minutes=round((time.time() - t0) / 60, 1))
    print("[18]", verdict)
    print("calibration:", calib)
